<?php

namespace App\Rules;

use Closure;
use Illuminate\Contracts\Validation\ValidationRule;

/**
 * Запрещает адреса из link-local: IPv4 169.254.0.0/16 и IPv6 fe80::/10.
 *
 * Почему именно этот диапазон, а не «всё внутреннее». Наблюдение за собственной
 * инфраструктурой — цель проекта (CAP-6), и на ступени 5 сервисы уедут в
 * кластер с адресами RFC1918. Глухой запрет приватных диапазонов зарезал бы
 * основной сценарий. В link-local легитимной проверки нет вовсе, зато по
 * 169.254.169.254 живёт служба метаданных облака, откуда достают учётные данные
 * инстанса.
 *
 * Граница ответственности. Правило смотрит только на литерал адреса в строке.
 * Имя, которое резолвится в link-local, оно пропустит — и это не дыра в
 * правиле, а следствие того, что резолв происходит в момент запроса, а не в
 * момент заведения проверки. Настоящая защита живёт у исполнителя (Story 1.5):
 * проверка после резолва, запрет редиректов на запрещённые диапазоны и
 * повторный резолв перед соединением. Здесь — гигиена ввода, не более.
 */
final class NotLinkLocalAddress implements ValidationRule
{
    public function validate(string $attribute, mixed $value, Closure $fail): void
    {
        if (! is_string($value)) {
            return;
        }

        $host = parse_url($value, PHP_URL_HOST);

        if (! is_string($host) || $host === '') {
            // Формат строки — забота правила url:http,https, не этого.
            return;
        }

        // Литерал IPv6 в URL приходит в квадратных скобках: http://[fe80::1]/.
        $host = trim($host, '[]');

        $packed = @inet_pton($host);

        if ($packed === false) {
            // Имя, а не адрес. Резолв — этап исполнителя.
            return;
        }

        if ($this->isLinkLocal($packed)) {
            $fail('Адрес из диапазона link-local проверять нельзя: там живёт служба метаданных облака.');
        }
    }

    /**
     * Сравнение идёт по упакованному виду, а не по строке: сокращённые формы
     * IPv6 (fe80::1 и fe80:0:0:0:0:0:0:1) на строках разошлись бы, на байтах
     * совпадают.
     *
     * inet_pton строгий: восьмеричную и целочисленную записи IPv4
     * (0251.0376.0251.0376, 2851995134) он не принимает, и такая строка уходит
     * отсюда как имя. Дырой это не становится — те же записи не принимает и
     * net.ParseIP в Go, то есть исполнитель ступени 1 их не резолвит, — но
     * рассчитывать на это правило как на границу нельзя, граница в Story 1.5.
     */
    private function isLinkLocal(string $packed): bool
    {
        $bytes = array_values(unpack('C*', $packed));

        if (count($bytes) === 4) {
            return $bytes[0] === 169 && $bytes[1] === 254;
        }

        // IPv4, записанный как IPv6: ::ffff:169.254.169.254 — те же четыре
        // байта в хвосте, тот же адрес на проводе.
        if ($this->isIpv4Mapped($bytes)) {
            return $bytes[12] === 169 && $bytes[13] === 254;
        }

        // fe80::/10 — старшие десять бит: байт fe и два старших бита второго.
        return $bytes[0] === 0xFE && ($bytes[1] & 0xC0) === 0x80;
    }

    /**
     * @param  list<int>  $bytes
     */
    private function isIpv4Mapped(array $bytes): bool
    {
        for ($i = 0; $i < 10; $i++) {
            if ($bytes[$i] !== 0) {
                return false;
            }
        }

        return $bytes[10] === 0xFF && $bytes[11] === 0xFF;
    }
}
