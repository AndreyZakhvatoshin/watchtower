<?php

return [

    /*
    |--------------------------------------------------------------------------
    | Токены исполнителя
    |--------------------------------------------------------------------------
    |
    | Список, а не одно значение: AD-13 требует ротируемости токена, а смена
    | одного значения означала бы окно, в котором ядро и исполнитель разошлись.
    | Со списком новый токен добавляется выкатом, исполнитель переводится на
    | него, старый убирается следующим выкатом — одновременность не нужна.
    |
    | Пустые элементы отбрасываются: строка «abc,» не должна превращаться
    | в «принимаем пустой токен». Пустой список означает отказ всем — отказ
    | закрытый, забытая переменная окружения лишает доступа, а не открывает его.
    |
    | env() читается здесь и только здесь (конвенция «Конфигурация»): вызов
    | env() вне файлов конфигурации вернёт null при config:cache — молча.
    |
    */

    'worker_tokens' => array_values(array_filter(
        array_map('trim', explode(',', (string) env('WORKER_TOKENS', ''))),
        static fn (string $token): bool => $token !== '',
    )),

];
